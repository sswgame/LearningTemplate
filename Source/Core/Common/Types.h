#pragma once
#include <cstdint>

/**
 * @file Types.h
 * @brief 크기가 고정된 기본 자료형(Primitive Types)에 대한 간결한 별칭(Alias)을 정의합니다.
 * @details std::int32_t와 같은 긴 표준 타이핑 대신 int32 등의 직관적인 심볼을 사용하기 위함입니다.
 */

// ============================================================================
// [부호 있는 정수형 (Signed Integers)]
// ============================================================================
using int8	= std::int8_t;
using int16 = std::int16_t;
using int32 = std::int32_t;
using int64 = std::int64_t;

// ============================================================================
// [부호 없는 정수형 (Unsigned Integers)]
// ============================================================================
using uint8	 = std::uint8_t;
using uint16 = std::uint16_t;
using uint32 = std::uint32_t;
using uint64 = std::uint64_t;

// ============================================================================
// [부동 소수점 (Floating Point)]
// ============================================================================
using float32 = float;
using float64 = double;

// ============================================================================
// [문자형 (Characters)]
// ============================================================================
using utf8	= char;     // ASCII 및 UTF-8 호환 문자형
using utf16 = wchar_t;  // Windows API 호환 와이드 문자형
