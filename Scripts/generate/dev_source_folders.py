"""
Scripts/generate/dev_source_folders.py

Config/Rules/Layers/DevFolders.json(개발 전용 소스 자리의 단일 출처)을 읽어 C++ 헤더(sw/config/DevSourceFolders.gen.h)를 생성합니다.
개발 등록 매크로 · 테스트 전역 변수의 경로 검사(`Core/Foundation/DevSourcePath.h`)가 이 표를 읽는다. CMake(`ExcludedSources.cmake`)는 같은 JSON 의
`_devFolderAllowed` 로 배포에서 `Dev/` 를 뺀다 — 자리를 두 곳에 적지 않는다.
"""

from __future__ import annotations

import json
from pathlib import Path

from generate.generator_output import CodeGenerator, GeneratorError, write_generated_file
from common.paths import get_project_root

TAG = "DevSourceFolders"
CONFIG_RELATIVE = "Config/Rules/Layers/DevFolders.json"
SECTIONS = ("_devFolderAllowed", "_devModuleRoots", "_editorFolderAllowed")
SOURCE_PREFIX = "Source/"


def load_tables(root: Path) -> dict[str, list[str]]:
    """표마다 `Source/` 를 뗀 접두어 목록(정렬)입니다. 없는 폴더 · `Source/` 밖 · `/` 로 끝나지 않는 줄은 오류로 멈춘다."""
    try:
        data = json.loads((root / CONFIG_RELATIVE).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exception:
        raise GeneratorError(f"{CONFIG_RELATIVE}: {exception}") from exception
    tables: dict[str, list[str]] = {}
    for section in SECTIONS:
        rows = data.get(section)
        if not isinstance(rows, dict) or not rows:
            raise GeneratorError(f"{CONFIG_RELATIVE}: {section} must be a non-empty object")
        prefixes = []
        for prefix in rows:
            if not prefix.startswith(SOURCE_PREFIX) or not prefix.endswith("/") or "\\" in prefix or '"' in prefix:
                raise GeneratorError(f"{CONFIG_RELATIVE}: {section} '{prefix}' must be a Source/ folder ending with /")
            if not (root / prefix).is_dir():
                raise GeneratorError(f"{CONFIG_RELATIVE}: {section} '{prefix}' does not exist - remove the line if the folder moved")
            prefixes.append(prefix[len(SOURCE_PREFIX):])
        tables[section] = sorted(prefixes)
    return tables


def make_header_text(tables: dict[str, list[str]]) -> str:
    def array(name: str, section: str) -> str:
        items = ", ".join(f'"{prefix}"' for prefix in tables[section])
        return f"    inline constexpr const char* {name}[] = {{ {items} }};"

    return f"""#pragma once
// AUTO-GENERATED by Scripts/generate/dev_source_folders.py — do not edit.
// SSOT: {CONFIG_RELATIVE} (접두어는 `Source/` 기준, 구분자는 `/`)

namespace sw
{{
    /** @brief `Dev/` 단위 폴더를 둘 수 있는 자리입니다. `Dev/` 로 끝나면 그 폴더 하나, 아니면 그 아래 어느 `Dev/` 든이다(`_devFolderAllowed`). */
{array("kArrDevFolderPrefix", "_devFolderAllowed")}
    /** @brief 통째로 개발 전용인 모듈 폴더입니다(`_devModuleRoots`). */
{array("kArrDevModuleRoot", "_devModuleRoots")}
    /** @brief 그 아래 `Editor/` 폴더가 에디터 확장 모듈인 자리입니다(`_editorFolderAllowed`). */
{array("kArrEditorFolderPrefix", "_editorFolderAllowed")}
}} // namespace sw
"""


def generate_dev_source_folders(header_path: Path) -> None:
    write_generated_file(header_path, make_header_text(load_tables(get_project_root())), tag=TAG)


class DevSourceFoldersGenerator(CodeGenerator):
    def generate(self, output_dir: Path, game_name: str) -> None:
        generate_dev_source_folders(output_dir / "DevSourceFolders.gen.h")
