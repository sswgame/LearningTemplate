#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Scripts/generate/editor_layers.py

에디터 층 표(`Config/Rules/Layers/EditorLayers.toml`)를 CMake 가 읽는 `EditorLayers.cmake` 로 옮긴다.

**왜 린트가 아니라 빌드인가.** `Source/Editor` 의 폴더는 층이고 아래 층은 위 층의 헤더를 include 하지 못한다. 이 규칙은 예전에 린트 게이트가
`#include` 글자를 읽어 막았다. 지금은 `Source/Editor/CMakeLists.txt` 가 티어마다 OBJECT 라이브러리(부분)로 짓고, 부분마다 자기 티어보다 위 층의
모든 헤더 자리에 `#error` 껍데기를 먼저 놓는다 — 위 층 헤더를 include 하면 컴파일이 멈춘다(전이 include 도 같다). 표는 여기서 한 번만 읽고
CMake 는 결과를 읽는다(`project_constants.py` → `ConfigVars.cmake` 와 같은 방식).

표가 폴더와 어긋나도 멈춘다(configure 가 서지 않는다) — 표에 없는 폴더는 티어를 정하고 넣고, 폴더가 사라진 줄은 지운다.

층 이름: `Common/<하위 폴더>`(Common 바로 아래 파일은 `Common`), 그 밖의 최상위 폴더, `Source/Editor` 바로 아래 파일은 `<root>`.

  python Scripts/generate/editor_layers.py <출력 .cmake 파일>
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path
from typing import Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # Scripts

from common.project_constants import DIR_SOURCE_EDITOR  # noqa: E402
from generate.generator_output import GeneratorError, run_generator, write_generated_file  # noqa: E402
from common.paths import get_project_root  # noqa: E402

TAG = "EditorLayers"
RULE_FILE = Path(__file__).resolve().parents[2] / "Config" / "Rules" / "Layers" / "EditorLayers.toml"
ROOT_LAYER_NAME = "<root>"
COMMON_FOLDER = "Common"

HEADER = """# ==============================================================================
# AUTO-GENERATED by Scripts/generate/editor_layers.py — do not edit.
#
# 출처: Config/Rules/Layers/EditorLayers.toml 의 [tier] · [prelude] · [panelViewBan] · [panelViewAllowed] 와 Source/Editor 의 폴더.
# 쓰는 곳: Source/Editor/CMakeLists.txt — 티어마다 부분을 짓고 위 층 헤더 자리에 #error 껍데기를 놓는다.
# ==============================================================================
"""


def _list_actual_layers(editor_dir: Path) -> list[str]:
    """`Source/Editor` 의 폴더에서 층 이름을 뽑는다."""
    list_layer: list[str] = []
    if any(child.is_file() for child in editor_dir.iterdir()):
        list_layer.append(ROOT_LAYER_NAME)
    for child in sorted(editor_dir.iterdir()):
        if not child.is_dir():
            continue
        if child.name != COMMON_FOLDER:
            list_layer.append(child.name)
            continue
        if any(entry.is_file() for entry in child.iterdir()):
            list_layer.append(COMMON_FOLDER)
        list_layer.extend(f"{COMMON_FOLDER}/{entry.name}" for entry in sorted(child.iterdir()) if entry.is_dir())
    return list_layer


def read_panel_view_ban(data: dict, root: Path, list_actual: list[str]) -> tuple[str, list[str], list[str]]:
    """`[panelViewBan]` 의 층 · 정규식과 `[panelViewAllowed]` 의 헤더 — CMake 가 Panels View 부분에 껍데기를 놓는다. 표가 낡으면 멈춘다."""
    try:
        layer: str = data["panelViewBan"]["layer"]
        list_pattern: list[str] = data["panelViewBan"]["patterns"]
        map_allowed: dict[str, str] = data["panelViewAllowed"]
    except KeyError as exception:
        raise GeneratorError(f"{RULE_FILE.name}: [panelViewBan] patterns 와 [panelViewAllowed] 가 있어야 한다 ({exception!r})") from exception
    if layer not in list_actual:
        raise GeneratorError(f"[panelViewBan] layer '{layer}' 가 에디터 층이 아니다")
    for pattern in list_pattern:
        if any(character in pattern for character in '\\";$'):
            raise GeneratorError(f"[panelViewBan] 의 정규식에 CMake 글자로 옮기지 못하는 문자가 있다: {pattern}")
        re.compile(pattern)
    for header, reason in map_allowed.items():
        if not (root / "Source" / header).is_file():
            raise GeneratorError(f"[panelViewAllowed] 의 파일이 없습니다: {header} — 표에서 지우거나 경로를 고치세요")
        if not reason or not any(re.search(pattern, header) for pattern in list_pattern):
            raise GeneratorError(f"[panelViewAllowed] 의 {header}: 까닭이 비었거나 금지 폴더 밖이다(낡은 줄) — 표에서 지우세요")
    return layer, list_pattern, list(map_allowed)


def generate_editor_layers(output_path: Path) -> None:
    try:
        data = tomllib.loads(RULE_FILE.read_text(encoding="utf-8"))
        map_tier: dict[str, int] = data["tier"]
    except (OSError, tomllib.TOMLDecodeError, KeyError) as exception:
        raise GeneratorError(f"{RULE_FILE.name}: 읽지 못했다 ({exception!r}) — [tier] 표가 있어야 한다") from exception
    root = get_project_root()
    editor_dir = root / DIR_SOURCE_EDITOR
    list_actual = _list_actual_layers(editor_dir)
    list_missing = [layer for layer in list_actual if layer not in map_tier]
    list_stale = [layer for layer in map_tier if layer not in list_actual]
    if list_missing:
        raise GeneratorError(f"티어 표에 없는 에디터 층: {', '.join(list_missing)} — {RULE_FILE.name} 의 [tier] 에 티어를 정해 넣으세요")
    if list_stale:
        raise GeneratorError(f"폴더가 없는 티어 표 줄: {', '.join(list_stale)} — {RULE_FILE.name} 의 [tier] 에서 지우세요")
    for include in data.get("prelude", {}):
        if not include.startswith("Editor/") or not (root / "Source" / include).is_file():
            raise GeneratorError(f"[prelude] 의 파일이 없습니다: {include}")
    panel_view_layer, list_ban_pattern, list_allowed = read_panel_view_ban(data, root, list_actual)

    list_tier = sorted(set(map_tier.values()))
    list_line = [HEADER.rstrip("\n"), "", f'set(SW_EDITOR_TIER_LIST "{";".join(str(tier) for tier in list_tier)}")']
    for tier in list_tier:
        list_layer = [layer for layer in list_actual if map_tier[layer] == tier]
        list_line.append(f'set(SW_EDITOR_TIER_{tier}_LAYERS "{";".join(list_layer)}")')
    list_line.append(f'set(SW_EDITOR_PRELUDE_HEADERS "{";".join(data.get("prelude", {}))}")')
    list_line.append(f'set(SW_EDITOR_PANEL_VIEW_LAYER "{panel_view_layer}")')
    list_line.append(f'set(SW_EDITOR_PANEL_VIEW_BAN_REGEX "{";".join(list_ban_pattern)}")')
    list_line.append(f'set(SW_EDITOR_PANEL_VIEW_ALLOWED_HEADERS "{";".join(list_allowed)}")')
    list_line.append("")
    write_generated_file(output_path, "\n".join(list_line), tag=TAG, summary=f"{len(list_actual)} layers · {len(list_tier)} tiers")


def main(argv: Sequence[str] | None = None) -> int:
    return run_generator(argv, tag=TAG, description="에디터 층 표 → CMake 변수",
                        add_arguments=lambda parser: parser.add_argument("output", type=Path, help="쓸 .cmake 파일"),
                        generate=lambda args: generate_editor_layers(args.output))


if __name__ == "__main__":
    sys.exit(main())
