r"""
Scripts/generate/GenerateShippingHostDefaults.py

커밋된 엔진 설정과 활성 게임의 프리셋(Config/Game/<게임>.json)을 읽어 Shipping 빌드용 C++ 헤더 둘로 생성합니다.
엔진 설정은 ShippingHostDefaults.h, 게임 프리셋(팩 루트 하나)은 ShippingGameDefaults.h — 게임 헤더는 Shipping 만 include 하므로 Dev 에서 활성 게임을 바꿔도
엔진 TU 가 다시 컴파일되지 않습니다(Dev 는 실행할 때 게임을 고른다, `GameSelection`).

사용법:
  python Scripts/generate/GenerateShippingHostDefaults.py <engine_header_path> <game_header_path> <game_preset_path>
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.Constants import kFileRuntimeEngineConfig  # noqa: E402
from generate.GeneratedFile import GeneratorError, runGenerator, writeGeneratedFile  # noqa: E402
from common.Paths import getProjectRoot  # noqa: E402

kTag = "GenerateShippingHostDefaults"


def escapeRawStringInternal(text: str) -> str:
    """JSON 문자열을 C++ raw string literal로 이스케이프합니다."""
    delimiter = "swcfg"
    while f"){delimiter}\"" in text:
        delimiter += "x"
    return f'R"{delimiter}({text}){delimiter}"'


def generateShippingHostDefaults(outputPath: Path, gameOutputPath: Path, gamePresetPath: str) -> None:
    """
    엔진 설정과 게임 프리셋을 읽어 C++ 헤더 둘(ShippingHostDefaults.h · ShippingGameDefaults.h)을 생성합니다.
    """
    projectRoot = getProjectRoot()
    enginePath = projectRoot / kFileRuntimeEngineConfig
    gamePath = projectRoot / gamePresetPath

    if not enginePath.is_file():
        raise GeneratorError(f"Engine config file not found: {enginePath}")
    if not gamePath.is_file():
        raise GeneratorError(f"Game config file not found: {gamePath}")

    try:
        engineJson = enginePath.read_text(encoding="utf-8").strip()
        json.loads(engineJson)  # 유효성 검증
    except (OSError, ValueError) as exception:
        raise GeneratorError(f"Failed to parse engine config {enginePath}: {exception}") from exception

    try:
        gameJson = gamePath.read_text(encoding="utf-8").strip()
        gameData = json.loads(gameJson)
    except (OSError, ValueError) as exception:
        raise GeneratorError(f"Failed to parse game config {gamePath}: {exception}") from exception
    # 프리셋은 팩 루트 하나다 — 나머지 설정은 팩의 gamesettings.xml 이 가진다. 다른 키가 구워지면 읽는 쪽이 없는 값이 Shipping 에만 남는다.
    if not isinstance(gameData, dict) or set(gameData) != {"_packRoot"}:
        raise GeneratorError(f"Game preset {gamePath} must contain only `_packRoot` (other settings belong in the pack's data/gamesettings.xml)")

    content = f"""#pragma once
// AUTO-GENERATED by GenerateShippingHostDefaults.py — do not edit.
// SSOT: committed {kFileRuntimeEngineConfig}

namespace sw::shipping_host
{{
	inline constexpr const char* kEngineConfigJSON = {escapeRawStringInternal(engineJson)};
}}
"""
    gameContent = f"""#pragma once
// AUTO-GENERATED by GenerateShippingHostDefaults.py — do not edit.
// SSOT: committed {gamePresetPath}

namespace sw::shipping_host
{{
	inline constexpr const char* kGameConfigJSON = {escapeRawStringInternal(gameJson)};
}}
"""

    writeGeneratedFile(outputPath, content, tag=kTag, bReportUnchanged=False)
    writeGeneratedFile(gameOutputPath, gameContent, tag=kTag, bReportUnchanged=False)


def main(argv: Sequence[str] | None = None) -> int:
    def addArgumentsInternal(parser: argparse.ArgumentParser) -> None:
        parser.add_argument("output", type=Path, help="엔진 설정 헤더(ShippingHostDefaults.h)")
        parser.add_argument("gameOutput", type=Path, help="게임 프리셋 헤더(ShippingGameDefaults.h)")
        parser.add_argument("gamePreset", help="게임 프리셋(저장소 기준 — Config/Game/<게임>.json)")

    return runGenerator(argv, tag=kTag, description="엔진 설정 + 게임 프리셋 → Shipping 기본값 C++ 헤더",
                        addArguments=addArgumentsInternal,
                        generate=lambda args: generateShippingHostDefaults(args.output, args.gameOutput, args.gamePreset))


if __name__ == "__main__":
    sys.exit(main())
