#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Scripts/generate/toolchain_cmake.py

`Config/Environment/toolchain_config.json` 을 CMake 가 바로 읽을 수 있는 `set()` 목록으로 찍습니다.

**왜 CMake 가 JSON 을 직접 파싱하지 않나.** 이 JSON 은 `environment.py` 가 **쓰는** 파일이다. CMake 여러 곳이
각자 파싱하면 같은 키를 상수와 리터럴 두 가지로 적게 되고, 한쪽만 바뀌는 날이 온다. 쓰는 쪽이 파이썬이니 **읽는 모양도
파이썬이 준다** — 이 저장소가 `project_constants.py` → `ConfigVars.cmake`
로 하고 있는 것과 같다.

**키 목록을 여기서도 들지 않는다** — JSON 에 있는 키를 그대로 `SW_TOOLCHAIN_<KEY 대문자>` 로 찍는다.
`environment.py` 가 키를 하나 더하면 CMake 에서 바로 쓸 수 있다.

(`FindLlvmBin.cmake` 는 그대로 둔다 — vcpkg 오버레이 생성(`VcpkgTriplets.cmake`)이 `project()` 앞에서 불러
이 생성 파일이 아직 없을 때도 성립해야 한다. 그래서 저장소 루트의 JSON 을 `sw_require_json_value`(`cmake/Config/JsonValue.cmake`)로
직접 읽는 코드가 거기 있는 것이다.)

Usage:
  python Scripts/generate/toolchain_cmake.py <output_cmake_file>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.project_constants import DIR_CONFIG_ENV, FILE_TOOLCHAIN_CONFIG  # noqa: E402
from generate.generator_output import GeneratorError, format_cmake_set, run_generator, write_generated_file  # noqa: E402
from common.paths import get_project_root  # noqa: E402

TAG = "ToolchainCMake"

HEADER = """# ==============================================================================
# AUTO-GENERATED by Scripts/generate/toolchain_cmake.py — do not edit.
# SSOT: {relPath}  (environment.py 가 쓰는 파일)
#
# JSON 의 키가 그대로 SW_TOOLCHAIN_<대문자> 변수가 된다. 없는 키는 변수도 없다 —
# CMake 에서 정의되지 않은 변수는 빈 값이므로 `if(X AND EXISTS "${{X}}")` 가 그대로 동작한다.
# ==============================================================================
"""


def _to_cmake_name(key: str) -> str:
    """JSON 키를 CMake 변수 이름으로. `llvm_path` → `SW_TOOLCHAIN_LLVM_PATH`."""
    return "SW_TOOLCHAIN_" + key.upper()


def generate_toolchain_cmake(output_path: Path, project_root: Path | None = None) -> None:
    root = (project_root or get_project_root()).resolve()
    rel_path = f"{DIR_CONFIG_ENV}/{FILE_TOOLCHAIN_CONFIG}"
    config_path = root / rel_path

    list_line: list[str] = [HEADER.format(rel_path=rel_path)]

    if not config_path.is_file():
        # 없는 것도 답이다 — Environment 가 아직 안 돌았거나 도구를 못 찾은 상태다.
        # CMake 쪽 폴백(find_program 등)이 그대로 동작하도록 변수를 하나도 만들지 않는다.
        list_line += ["set(SW_TOOLCHAIN_CONFIG_FOUND FALSE)", ""]
        write_generated_file(output_path, "\n".join(list_line), tag=TAG, summary=f"{rel_path} 없음 — 빈 변수 파일")
        return

    try:
        map_config = json.loads(config_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exception:
        raise GeneratorError(f"{rel_path} 을 읽지 못했습니다: {exception}") from exception

    list_line.append("set(SW_TOOLCHAIN_CONFIG_FOUND TRUE)")
    list_line += [format_cmake_set(_to_cmake_name(key), map_config[key]) for key in sorted(map_config)]
    list_line.append("")
    write_generated_file(output_path, "\n".join(list_line), tag=TAG, summary=f"{len(map_config)} keys")


def main(argv: Sequence[str] | None = None) -> int:
    return run_generator(argv, tag=TAG, description="toolchain_config.json → CMake set() 목록",
                        add_arguments=lambda parser: parser.add_argument("output", type=Path, help="쓸 .cmake 파일"),
                        generate=lambda args: generate_toolchain_cmake(args.output))


if __name__ == "__main__":
    sys.exit(main())
