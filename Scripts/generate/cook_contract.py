"""
Scripts/generate/cook_contract.py

Config/Engine/CookContract.json(쿠킹 표의 단일 출처)을 읽어 C++ 헤더(sw/config/CookContract.gen.h)를 생성합니다.

생성물은 X-macro 들이다 — `SW_RHI_BACKEND_TABLE( X )` · `SW_RHI_BACKEND_ORDER_<플랫폼>( X )` · `SW_RHI_SCENARIO_BACKENDS_<플랫폼>( X )` · `SW_TARGET_EXCLUDED_GROUP_TABLE( X )`. 쓰는 쪽(ArgumentList.xxx ·
RHIBackendUtil · ShaderCooker · PackCooker · AssetPaths)이 X 를 정의해 펼치므로, 줄이 늘면 그 자리들이 같이 늘어난다. Python 쿠커
(Pack 등)는 같은 파일을 `CookContractSpec` 으로 읽는다.

Usage:
  python Scripts/generate/cook_contract.py <output_header_path> <output_cmake_path>
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.cook_table import CookContractSpec, COOK_CONTRACT_CONFIG_RELATIVE  # noqa: E402
from generate.generator_output import GeneratorError, run_generator, write_generated_file  # noqa: E402
from common.paths import get_project_root  # noqa: E402

TAG = "CookContract"


def _emit_macro(macro_name: str, list_row: list[str]) -> str:
    """`#define NAME( X ) \\` 와 줄마다 `X( ... )` 를 이어 붙인 X-macro 정의를 만듭니다."""
    lines = [f"#define {macro_name}( X ) \\"]
    for row_index, row in enumerate(list_row):
        continuation = " \\" if row_index + 1 < len(list_row) else ""
        lines.append(f"    X( {row} ){continuation}")
    return "\n".join(lines)


def make_header_text(spec: CookContractSpec) -> str:
    """생성 헤더의 전체 글입니다."""
    list_backend_row = [
        ", ".join(
            [backend.name, f'"{backend.shader_folder}"', backend.shader_target, backend.command_line_argument, f'"{backend.command_line_name}"']
        )
        for backend in spec.list_backend
    ]
    backend_order_text = "\n\n".join(_emit_macro(f"SW_RHI_BACKEND_ORDER_{platform}", list(list_name)) for platform, list_name in spec.map_backend_order_by_platform.items())
    backend_order_text += "\n\n" + "\n\n".join(_emit_macro(f"SW_RHI_SCENARIO_BACKENDS_{platform}", list(list_name)) for platform, list_name in spec.map_scenario_backends_by_platform.items())
    list_exclusion_row = [f"{target}, {group}" for target, list_group in spec.map_excluded_kind_by_target.items() for group in list_group]
    list_unit_limit_row = [f"{backend.shader_target}, {backend.stage_texture_unit_limit}" for backend in spec.list_backend if backend.stage_texture_unit_limit is not None]
    unit_limit_define_text = "\n".join(f"#define SW_STAGE_TEXTURE_UNIT_LIMIT_{backend.shader_target} {backend.stage_texture_unit_limit}"
                                    for backend in spec.list_backend if backend.stage_texture_unit_limit is not None)
    return f"""#pragma once
// AUTO-GENERATED by Scripts/generate/cook_contract.py — do not edit.
// SSOT: {COOK_CONTRACT_CONFIG_RELATIVE}
//
// 쿠킹 표 둘의 C++ 쪽 표현이다. 엔진의 쿠커(PackCooker · ShaderCooker)가 이것을 읽는다.

/**
 * @brief RHI 백엔드 표입니다. 줄 순서 = RHIBackend 열거값입니다.
 * @details X( Backend, ShaderFolder, ShaderTarget, CommandLineArgument, CommandLineName )
 *          Backend = RHIBackend 열거자, ShaderFolder = 셰이더 바이너리 폴더 이름, ShaderTarget = ShaderTargetFormat 열거자,
 *          CommandLineArgument = CommandLineArgument 열거자, CommandLineName = 명령줄 플래그 · 쿠커가 받는 백엔드마다 하나뿐인 이름(소문자 문자열).
 */
{_emit_macro("SW_RHI_BACKEND_TABLE", list_backend_row)}

/** @brief 명령줄 · 설정이 백엔드를 고르지 않았을 때 쓰는 RHIBackend 열거자입니다. */
#define SW_RHI_BACKEND_DEFAULT {spec.default_backend.name}

// 플랫폼마다 이 빌드가 만들 수 있는 백엔드와 건너갈 순서입니다. 맨 앞이 그 플랫폼의 기본이고, X( Backend ) 입니다.
{backend_order_text}

/**
 * @brief 셰이더 단계 하나가 쓸 수 있는 텍스처 단위 수입니다(`stage_texture_unit_limit`). X( ShaderTarget, Limit ) — 한도가 null 인 백엔드(텍스처가 고정 칸이 아니다)는 줄이 없습니다.
 * @details 쿠킹의 계약 검사(`ShaderBindingValidatorIssue`)가 넘는 바이너리를 오류로 세고, GL 장치 초기화가 이보다 작은 드라이버를 거절합니다.
 */
{_emit_macro("SW_STAGE_TEXTURE_UNIT_LIMIT_TABLE", list_unit_limit_row)}

// 같은 값의 대상별 상수입니다(`SW_STAGE_TEXTURE_UNIT_LIMIT_<ShaderTarget>`) — 장치 검사(shaderslot::gl::kFragmentTextureUnitBudget)가 constexpr 로 읽습니다.
{unit_limit_define_text}

/**
 * @brief 빌드 타깃이 패키지에서 빼고 런타임이 읽지 않는 에셋 묶음입니다(`target_excluded_asset_kinds`).
 * @details X( Target, Group ) — Target = 빌드 타깃 이름(`Server`), Group = 엔진 에셋 종류의 제외 묶음 이름(`AssetTypeDef::_excludeGroup`).
 *          어느 파일이 그 묶음인지는 종류 표(`AssetTypeRegistry::findExcludeGroup`)가 접미사로 정한다.
 */
{_emit_macro("SW_TARGET_EXCLUDED_GROUP_TABLE", list_exclusion_row)}
"""


def make_cmake_text(spec: CookContractSpec) -> str:
    """CMake 가 include 하는 백엔드 표 — `SW_RHI_BACKEND_NAMES` 와 이름마다 `SW_RHI_BACKEND_<이름>_<칸>`(cmake/Engine/RhiBackends.cmake 가 쓴다)."""
    list_line = [f"# AUTO-GENERATED by Scripts/generate/cook_contract.py — do not edit. SSOT: {COOK_CONTRACT_CONFIG_RELATIVE}",
                f"set(SW_RHI_BACKEND_NAMES {' '.join(backend.name for backend in spec.list_backend)})"]
    for backend in spec.list_backend:
        prefix = f"SW_RHI_BACKEND_{backend.name}"
        list_line += [f"set({prefix}_MODULE {backend.module_name})",
                     f"set({prefix}_SOURCE_FOLDER {backend.source_folder})",
                     f"set({prefix}_GRAPHICS_LIBS {backend.graphics_libs})",
                     f"set({prefix}_SHIPPING_DEFINE {backend.shipping_define})",
                     f"set({prefix}_COMMAND_LINE_NAME {backend.command_line_name})"]
    return "\n".join(list_line) + "\n"


def generate_cook_contract(header_path: Path, cmake_path: Path) -> None:
    try:
        spec = CookContractSpec.load(get_project_root())
    except (FileNotFoundError, KeyError, ValueError) as exception:
        raise GeneratorError(f"{COOK_CONTRACT_CONFIG_RELATIVE}: {exception}") from exception
    write_generated_file(header_path, make_header_text(spec), tag=TAG)
    write_generated_file(cmake_path, make_cmake_text(spec), tag=TAG)


def main(argv: list[str] | None = None) -> int:
    def _add_arguments(parser: argparse.ArgumentParser) -> None:
        parser.add_argument("header", type=Path, help="쓸 C++ 헤더")
        parser.add_argument("cmake", type=Path, help="쓸 CMake 표(RHI 백엔드)")

    return run_generator(argv, tag=TAG, description="CookContract.json → C++ X-매크로 헤더 · CMake 백엔드 표",
                        add_arguments=_add_arguments,
                        generate=lambda args: generate_cook_contract(args.header, args.cmake))


if __name__ == "__main__":
    sys.exit(main())
