#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Scripts/generate/EditorLayers.py

에디터 층 표(`Config/Rules/Layers/EditorLayers.toml`)를 CMake 가 읽는 `EditorLayers.cmake` 로 옮긴다.

**왜 린트가 아니라 빌드인가.** `Source/Editor` 의 폴더는 층이고 아래 층은 위 층의 헤더를 include 하지 못한다. 이 규칙은 예전에 린트 게이트가
`#include` 글자를 읽어 막았다. 지금은 `Source/Editor/CMakeLists.txt` 가 티어마다 OBJECT 라이브러리(부분)로 짓고, 부분마다 자기 티어보다 위 층의
모든 헤더 자리에 `#error` 껍데기를 먼저 놓는다 — 위 층 헤더를 include 하면 컴파일이 멈춘다(전이 include 도 같다). 표는 여기서 한 번만 읽고
CMake 는 결과를 읽는다(`ProjectConstants.py` → `ConfigVars.cmake` 와 같은 방식).

표가 폴더와 어긋나도 멈춘다(configure 가 서지 않는다) — 표에 없는 폴더는 티어를 정하고 넣고, 폴더가 사라진 줄은 지운다.

층 이름: `Common/<하위 폴더>`(Common 바로 아래 파일은 `Common`), 그 밖의 최상위 폴더, `Source/Editor` 바로 아래 파일은 `<root>`.

  python Scripts/generate/EditorLayers.py <출력 .cmake 파일>
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path
from typing import Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # Scripts

from common.ProjectConstants import kDirSourceEditor  # noqa: E402
from generate.GeneratorOutput import GeneratorError, runGenerator, writeGeneratedFile  # noqa: E402
from common.Paths import getProjectRoot  # noqa: E402

kTag = "EditorLayers"
kRuleFile = Path(__file__).resolve().parents[2] / "Config" / "Rules" / "Layers" / "EditorLayers.toml"
kRootLayerName = "<root>"
kCommonFolder = "Common"

kHeader = """# ==============================================================================
# AUTO-GENERATED by Scripts/generate/EditorLayers.py — do not edit.
#
# 출처: Config/Rules/Layers/EditorLayers.toml 의 [tier] · [prelude] · [panelViewBan] · [panelViewAllowed] 와 Source/Editor 의 폴더.
# 쓰는 곳: Source/Editor/CMakeLists.txt — 티어마다 부분을 짓고 위 층 헤더 자리에 #error 껍데기를 놓는다.
# ==============================================================================
"""


def listActualLayersInternal(editorDir: Path) -> list[str]:
    """`Source/Editor` 의 폴더에서 층 이름을 뽑는다."""
    listLayer: list[str] = []
    if any(child.is_file() for child in editorDir.iterdir()):
        listLayer.append(kRootLayerName)
    for child in sorted(editorDir.iterdir()):
        if not child.is_dir():
            continue
        if child.name != kCommonFolder:
            listLayer.append(child.name)
            continue
        if any(entry.is_file() for entry in child.iterdir()):
            listLayer.append(kCommonFolder)
        listLayer.extend(f"{kCommonFolder}/{entry.name}" for entry in sorted(child.iterdir()) if entry.is_dir())
    return listLayer


def readPanelViewBan(data: dict, root: Path, listActual: list[str]) -> tuple[str, list[str], list[str]]:
    """`[panelViewBan]` 의 층 · 정규식과 `[panelViewAllowed]` 의 헤더 — CMake 가 Panels View 부분에 껍데기를 놓는다. 표가 낡으면 멈춘다."""
    try:
        layer: str = data["panelViewBan"]["layer"]
        listPattern: list[str] = data["panelViewBan"]["patterns"]
        mapAllowed: dict[str, str] = data["panelViewAllowed"]
    except KeyError as exception:
        raise GeneratorError(f"{kRuleFile.name}: [panelViewBan] patterns 와 [panelViewAllowed] 가 있어야 한다 ({exception!r})") from exception
    if layer not in listActual:
        raise GeneratorError(f"[panelViewBan] layer '{layer}' 가 에디터 층이 아니다")
    for pattern in listPattern:
        if any(character in pattern for character in '\\";$'):
            raise GeneratorError(f"[panelViewBan] 의 정규식에 CMake 글자로 옮기지 못하는 문자가 있다: {pattern}")
        re.compile(pattern)
    for header, reason in mapAllowed.items():
        if not (root / "Source" / header).is_file():
            raise GeneratorError(f"[panelViewAllowed] 의 파일이 없습니다: {header} — 표에서 지우거나 경로를 고치세요")
        if not reason or not any(re.search(pattern, header) for pattern in listPattern):
            raise GeneratorError(f"[panelViewAllowed] 의 {header}: 까닭이 비었거나 금지 폴더 밖이다(낡은 줄) — 표에서 지우세요")
    return layer, listPattern, list(mapAllowed)


def generateEditorLayers(outputPath: Path) -> None:
    try:
        data = tomllib.loads(kRuleFile.read_text(encoding="utf-8"))
        mapTier: dict[str, int] = data["tier"]
    except (OSError, tomllib.TOMLDecodeError, KeyError) as exception:
        raise GeneratorError(f"{kRuleFile.name}: 읽지 못했다 ({exception!r}) — [tier] 표가 있어야 한다") from exception
    root = getProjectRoot()
    editorDir = root / kDirSourceEditor
    listActual = listActualLayersInternal(editorDir)
    listMissing = [layer for layer in listActual if layer not in mapTier]
    listStale = [layer for layer in mapTier if layer not in listActual]
    if listMissing:
        raise GeneratorError(f"티어 표에 없는 에디터 층: {', '.join(listMissing)} — {kRuleFile.name} 의 [tier] 에 티어를 정해 넣으세요")
    if listStale:
        raise GeneratorError(f"폴더가 없는 티어 표 줄: {', '.join(listStale)} — {kRuleFile.name} 의 [tier] 에서 지우세요")
    for include in data.get("prelude", {}):
        if not include.startswith("Editor/") or not (root / "Source" / include).is_file():
            raise GeneratorError(f"[prelude] 의 파일이 없습니다: {include}")
    panelViewLayer, listBanPattern, listAllowed = readPanelViewBan(data, root, listActual)

    listTier = sorted(set(mapTier.values()))
    listLine = [kHeader.rstrip("\n"), "", f'set(SW_EDITOR_TIER_LIST "{";".join(str(tier) for tier in listTier)}")']
    for tier in listTier:
        listLayer = [layer for layer in listActual if mapTier[layer] == tier]
        listLine.append(f'set(SW_EDITOR_TIER_{tier}_LAYERS "{";".join(listLayer)}")')
    listLine.append(f'set(SW_EDITOR_PRELUDE_HEADERS "{";".join(data.get("prelude", {}))}")')
    listLine.append(f'set(SW_EDITOR_PANEL_VIEW_LAYER "{panelViewLayer}")')
    listLine.append(f'set(SW_EDITOR_PANEL_VIEW_BAN_REGEX "{";".join(listBanPattern)}")')
    listLine.append(f'set(SW_EDITOR_PANEL_VIEW_ALLOWED_HEADERS "{";".join(listAllowed)}")')
    listLine.append("")
    writeGeneratedFile(outputPath, "\n".join(listLine), tag=kTag, summary=f"{len(listActual)} layers · {len(listTier)} tiers")


def main(argv: Sequence[str] | None = None) -> int:
    return runGenerator(argv, tag=kTag, description="에디터 층 표 → CMake 변수",
                        addArguments=lambda parser: parser.add_argument("output", type=Path, help="쓸 .cmake 파일"),
                        generate=lambda args: generateEditorLayers(args.output))


if __name__ == "__main__":
    sys.exit(main())
