#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Scripts/generate/ModuleLayers.py

모듈 층 표(`Config/Rules/Layers/<모듈>Layers.toml`)를 CMake 가 읽는 `<모듈>Layers.cmake` 로 옮긴다. 표 하나가 모듈 폴더 하나를 맡는다(`kListLayerTable`):
Engine(`Source/Engine`)과 GameFramework 런타임(`Source/GameFramework/Runtime`).

**왜 린트가 아니라 빌드인가.** include 는 글자라 예전에는 린트 게이트가 `#include "Engine/..."` 줄을 읽어 막았다(직접 include 만 보였다).
지금은 모듈의 CMakeLists 가 층마다 부분(OBJECT 라이브러리 — 오브젝트는 모듈 이미지 안)을 짓고, 부분마다 자기 층보다 위 층의
모든 헤더 자리에 `#error` 껍데기를 먼저 놓는다(`sw_addLayerStubs`) — 위 층 헤더를 include 하면 컴파일이 멈춘다(헤더를 거쳐 닿는 전이 include 도 같다).
에디터 층(`EditorLayers.py`)과 같은 방식이다.

파일마다 층을 표에서 정한다(키는 모듈 폴더 아래 경로 접두어, 가장 긴 것이 이긴다). 표에 없는 파일이 있으면 멈춘다(configure 가 서지 않는다).

  python Scripts/generate/ModuleLayers.py <모듈 이름> <출력 .cmake 파일>
"""

from __future__ import annotations

import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # Scripts

from common.Paths import getProjectRoot  # noqa: E402
from generate.GeneratorOutput import GeneratorError, runGenerator, writeGeneratedFile  # noqa: E402

kTag = "ModuleLayers"
kRuleDir = Path(__file__).resolve().parents[2] / "Config" / "Rules" / "Layers"
kSourceSuffix = {".cpp", ".c"}
kHeaderSuffix = {".h", ".hpp", ".inl", ".xxx"}


@dataclass(frozen=True)
class LayerTable:
    """층 표 하나 — 모듈 이름(출력 파일 · 표 파일 이름), 층을 매기는 폴더(`Source/` 기준), CMake 변수 머리."""
    _module: str
    _rootFolder: str
    _varPrefix: str

    def getRuleFile(self) -> Path:
        return kRuleDir / f"{self._module}Layers.toml"


kListLayerTable = (
    LayerTable("Engine", "Engine", "SW_ENGINE_TIER"),
    LayerTable("GameFramework", "GameFramework/Runtime", "SW_GAMEFRAMEWORK_TIER"),
)


def findLayerTable(module: str) -> LayerTable:
    for table in kListLayerTable:
        if table._module == module:
            return table
    raise GeneratorError(f"층 표가 없는 모듈 '{module}' — {', '.join(table._module for table in kListLayerTable)} 중 하나다")


def findTier(mapTier: dict[str, int], relative: str) -> int | None:
    """모듈 폴더 기준 경로의 층 — 가장 긴 접두어 키가 이긴다. 표에 없으면 None."""
    best: tuple[str, int] | None = None
    for key, tier in mapTier.items():
        if relative == key or relative.startswith(key + "/"):
            if best is None or len(key) > len(best[0]):
                best = (key, tier)
    return best[1] if best is not None else None


def generateModuleLayers(module: str, outputPath: Path) -> None:
    table = findLayerTable(module)
    ruleFile = table.getRuleFile()
    try:
        mapTier: dict[str, int] = tomllib.loads(ruleFile.read_text(encoding="utf-8"))["tier"]
    except (OSError, tomllib.TOMLDecodeError, KeyError) as exception:
        raise GeneratorError(f"{ruleFile.name}: 읽지 못했다 ({exception!r}) — [tier] 표가 있어야 한다") from exception
    rootDir = getProjectRoot() / "Source" / table._rootFolder
    mapSource: dict[int, list[str]] = {}
    mapHeader: dict[int, list[str]] = {}
    listUnknown: list[str] = []
    for path in sorted(rootDir.rglob("*")):
        if not path.is_file() or path.suffix not in kSourceSuffix | kHeaderSuffix:
            continue
        relative = path.relative_to(rootDir).as_posix()
        tier = findTier(mapTier, relative)
        if tier is None:
            listUnknown.append(relative)
            continue
        if path.suffix in kSourceSuffix:
            mapSource.setdefault(tier, []).append(relative)
        else:
            mapHeader.setdefault(tier, []).append(f"{table._rootFolder}/{relative}")
    if listUnknown:
        raise GeneratorError(f"층 표에 없는 {module} 파일: {', '.join(listUnknown[:20])} — {ruleFile.name} 의 [tier] 에 층을 정해 넣으세요")
    listStale = [key for key in mapTier if not (rootDir / key).exists()]
    if listStale:
        raise GeneratorError(f"폴더 · 파일이 없는 층 표 줄: {', '.join(listStale)} — {ruleFile.name} 의 [tier] 에서 지우세요")

    listTier = sorted(set(mapTier.values()))
    header = f"""# ==============================================================================
# AUTO-GENERATED by Scripts/generate/ModuleLayers.py — do not edit.
#
# 출처: Config/Rules/Layers/{ruleFile.name} 의 [tier] 와 Source/{table._rootFolder} 의 파일.
# 쓰는 곳: {module} 의 CMakeLists — 층마다 부분을 짓고 위 층 헤더 자리에 #error 껍데기를 놓는다(sw_addLayerStubs).
#   {table._varPrefix}_<N>_SOURCES : 그 층의 .cpp · .c(Source/{table._rootFolder} 기준)
#   {table._varPrefix}_<N>_HEADERS : 그 층의 헤더(Source 기준 — include 줄과 같은 모양)
# =============================================================================="""
    listLine = [header, "", f'set({table._varPrefix}_LIST "{";".join(str(tier) for tier in listTier)}")']
    for tier in listTier:
        listLine.append(f'set({table._varPrefix}_{tier}_SOURCES "{";".join(mapSource.get(tier, []))}")')
        listLine.append(f'set({table._varPrefix}_{tier}_HEADERS "{";".join(mapHeader.get(tier, []))}")')
    listLine.append("")
    fileCount = sum(len(v) for v in mapSource.values()) + sum(len(v) for v in mapHeader.values())
    writeGeneratedFile(outputPath, "\n".join(listLine), tag=f"{module}Layers", summary=f"{fileCount} files · {len(listTier)} tiers")


def main(argv: Sequence[str] | None = None) -> int:
    def addArguments(parser) -> None:
        parser.add_argument("module", help="층 표의 모듈 이름(Engine · GameFramework)")
        parser.add_argument("output", type=Path, help="쓸 .cmake 파일")

    return runGenerator(argv, tag=kTag, description="모듈 층 표 → CMake 변수", addArguments=addArguments,
                        generate=lambda args: generateModuleLayers(args.module, args.output))


if __name__ == "__main__":
    sys.exit(main())
