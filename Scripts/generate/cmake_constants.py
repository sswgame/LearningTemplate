#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Scripts/generate/cmake_constants.py

`Scripts/common/project_constants.py` 의 상수를 CMake 가 그대로 읽는 `set(SW_...)` 목록으로 찍습니다.

**목록을 여기서 들지 않는다.** `set(SW_...)` 줄을 손으로 적으면 CMake 변수 이름과 파이썬 상수 이름을 **두 번**
철자하게 되고, 어느 상수가 왜 빠졌는지 알 수 없게 된다(옆 `toolchain_cmake.py` 도 같은 이유로 JSON 키를
그대로 변환해 찍는다). `project_constants.py` 의 대문자 상수(PEP 8)는 **전부** 나간다. 이름은 `SW_` 만 붙는다:

    DIR_CONFIG_ENV        -> SW_DIR_CONFIG_ENV
    FILE_TOOLCHAIN_CONFIG -> SW_FILE_TOOLCHAIN_CONFIG
    CPP_ALL_EXTENSIONS    -> SW_CPP_ALL_EXTENSIONS   (집합/튜플은 CMake 리스트가 된다)

상수를 하나 더하면 CMake 에서 바로 쓸 수 있다 — 여기 고칠 것이 없다.

**경로를 합치지 않는다.** 같은 이름은 파이썬과 CMake 에서 같은 값(파일 이름)을 뜻해야 한다. 한 상수만 디렉터리를
붙여 내보내면, 그걸 모르는 자리가 `${SW_DIR_CONFIG_ENV}/${SW_FILE_PARSER_CONFIG}` 로 **디렉터리를 두 번** 붙이고,
없는 경로를 `if(EXISTS)` 가 조용히 걸러 내 **`parser_config.json` 이 바뀌어도 리플렉션 코드젠이 다시 돌지 않는다.**
합치는 일은 합칠 줄 아는 쪽(`ConfigConstants.h.in` · 호출부)이 한다.

Usage:
  python Scripts/generate/cmake_constants.py <output_cmake_file>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Any, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import project_constants as config_constants  # noqa: E402
from generate.generator_output import format_cmake_set, run_generator, write_generated_file  # noqa: E402

TAG = "CMakeConstants"

HEADER = """# ==============================================================================
# AUTO-GENERATED by Scripts/generate/cmake_constants.py — do not edit.
# SSOT: Scripts/common/project_constants.py
#
# 대문자 상수가 그대로 `SW_<상수 이름>` 변수가 된다. 상수를 더하면 변수도 생긴다 —
# 생성기에 적을 목록은 없다.
# ==============================================================================
"""


def _is_exportable(name: str, value: Any) -> bool:
    """
    내보낼 상수인가.

    대문자(PEP 8 상수) 모듈 수준 이름만 본다 — import 해 온 것(`Path` 등)과 내부 헬퍼는 제외한다.
    """
    if re.fullmatch(r"[A-Z][A-Z0-9_]*", name) is None:
        return False

    return isinstance(value, (str, int, float, bool, set, frozenset, list, tuple))


def generate_cmake_constants(output_file: Path) -> None:
    """공통 상수를 CMake `set(SW_...)` 구문으로 변환하여 지정된 파일에 저장합니다."""
    list_line: list[str] = [HEADER]

    map_exported: dict[str, str] = {}
    for name in sorted(vars(config_constants)):
        value = getattr(config_constants, name)
        if not _is_exportable(name, value):
            continue

        cmake_name = "SW_" + name
        map_exported[cmake_name] = name
        list_line.append(format_cmake_set(cmake_name, value))

    list_line.append("")
    write_generated_file(output_file, "\n".join(list_line), tag=TAG, summary=f"{len(map_exported)} constants")


def main(argv: Sequence[str] | None = None) -> int:
    return run_generator(argv, tag=TAG, description="project_constants.py → CMake set() 목록",
                        add_arguments=lambda parser: parser.add_argument("output", type=Path, help="쓸 .cmake 파일"),
                        generate=lambda args: generate_cmake_constants(args.output))


if __name__ == "__main__":
    sys.exit(main())
