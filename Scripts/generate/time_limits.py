"""
Scripts/generate/time_limits.py

Config/Dev/TimeLimits.json 의 `_scenario` · `_devTools` 를 C++ 상수 헤더(sw/config/TimeLimits.gen.h)로 옮긴다. 실행기 시한(`AutomationTimeLimits`)과 개발 도구 시한이
이 값을 쓰고, 파이썬(`common/time_limits.py`)도 같은 파일을 읽는다 — 시한을 두 곳에 적지 않는다. 상수로 굳히는 까닭은 대소 관계를 static_assert 로 지키기 위해서다.
스크립트 시한이 C++ 시한보다 길어야 하는 관계(`_scripts` → 체인 프로세스 시한)는 여기서 본다.
"""

from __future__ import annotations

import re
from pathlib import Path

from common.paths import get_project_root
from common.time_limits import TIME_LIMITS_PATH, get_chain_kill_seconds, read_time_limit_sections
from generate.generator_output import CodeGenerator, GeneratorError, write_generated_file

TAG = "TimeLimits"
KEY_SHAPE = re.compile(r"_([a-z][A-Za-z0-9]*)")
HEADER_SECTIONS = ("_scenario", "_devTools")


def to_constant_name(key: str) -> str:
    match = KEY_SHAPE.fullmatch(key)
    if match is None:
        raise GeneratorError(f"{TIME_LIMITS_PATH}: 칸 이름 '{key}' 는 `_` 접두 camelCase 여야 한다")
    name = match.group(1)
    return "k" + name[0].upper() + name[1:]


def require_script_limits(sections: dict, project_root: Path) -> None:
    """ctest 시한이 그 안에서 도는 App 의 체인 프로세스 시한보다 길어야 한다 — 짧으면 ctest 가 먼저 죽여 App 의 보고가 남지 않는다."""
    single_kill = get_chain_kill_seconds(1, project_root)
    scripts = sections["_scripts"]
    if scripts.get("_singleScenarioCtestSeconds", 0) <= single_kill:
        raise GeneratorError(f"{TIME_LIMITS_PATH}: _scripts._singleScenarioCtestSeconds 는 단일 시나리오 프로세스 시한({single_kill:g} 초)보다 길어야 한다")
    if scripts.get("_sequenceCtestSeconds", 0) <= 2 * single_kill:
        raise GeneratorError(f"{TIME_LIMITS_PATH}: _scripts._sequenceCtestSeconds 는 두 단계 묶음 시한({2 * single_kill:g} 초)보다 길어야 한다")


def make_header_text(sections: dict) -> str:
    list_line: list[str] = []
    for section in HEADER_SECTIONS:
        list_line.append(f"    // {section}")
        for key, value in sections[section].items():
            if isinstance(value, int):
                list_line.append(f"    inline constexpr uint32 {to_constant_name(key)} = {value}u;")
            else:
                list_line.append(f"    inline constexpr float64 {to_constant_name(key)} = {value!r};")
    body = "\n".join(list_line)
    return f"""#pragma once
// AUTO-GENERATED by Scripts/generate/time_limits.py — do not edit.
// SSOT: {TIME_LIMITS_PATH.as_posix()} (`_scenario` · `_devTools`)
#include "Core/Foundation/Types.h"

namespace sw::TimeLimitConfig
{{
{body}
}} // namespace sw::TimeLimitConfig
"""


def generate_time_limits(header_path: Path) -> None:
    project_root = get_project_root()
    sections = read_time_limit_sections(project_root)
    require_script_limits(sections, project_root)
    write_generated_file(header_path, make_header_text(sections), tag=TAG)


class TimeLimitsGenerator(CodeGenerator):
    def generate(self, output_dir: Path, game_name: str) -> None:
        generate_time_limits(output_dir / "TimeLimits.gen.h")
