"""
Scripts/generate/ProcessExitCodes.py

Config/Engine/ProcessExitCodes.json(프로세스 종료 코드 표의 단일 출처)을 읽어 C++ 헤더(sw/config/ProcessExitCodes.gen.h)와
CMake 표(ProcessExitCodes.cmake — `SW_EXIT_CODE_<name>`)를 생성합니다. 숫자는 JSON 에만 있다.

Usage:
  python Scripts/generate/ProcessExitCodes.py <output_header_path> <output_cmake_path>
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from generate.GeneratorOutput import GeneratorError, runGenerator, writeGeneratedFile  # noqa: E402
from common.Paths import getProjectRoot  # noqa: E402

kTag = "ProcessExitCodes"
kConfigRelative = "Config/Engine/ProcessExitCodes.json"


def loadRows() -> list[tuple[str, int, str]]:
    """(name, code, label) 줄 목록입니다. 이름 · 코드 · 라벨이 겹치거나 칸이 틀리면 오류로 멈춘다."""
    path = getProjectRoot() / kConfigRelative
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        listRow = [(str(row["name"]), int(row["code"]), str(row["label"])) for row in data["exit_codes"]]
    except (OSError, KeyError, TypeError, ValueError) as exception:
        raise GeneratorError(f"{kConfigRelative}: {exception}") from exception
    for column, kind in ((0, "name"), (1, "code"), (2, "label")):
        listValue = [row[column] for row in listRow]
        if len(set(listValue)) != len(listValue):
            raise GeneratorError(f"{kConfigRelative}: duplicate {kind} in exit_codes")
    if any(not name.isidentifier() for name, _, _ in listRow):
        raise GeneratorError(f"{kConfigRelative}: every name must be a C++ identifier")
    return listRow


def makeHeaderText(listRow: list[tuple[str, int, str]]) -> str:
    listEnumerator = "\n".join(f"        {name} = {code}," for name, code, _ in listRow)
    listCase = "\n".join(f'            case {code}:\n                return "{label}";' for _, code, label in listRow)
    return f"""#pragma once
// AUTO-GENERATED by Scripts/generate/ProcessExitCodes.py — do not edit.
// SSOT: {kConfigRelative}

namespace sw
{{
    /** @brief App 이 밖으로 내는 프로세스 종료 코드입니다. 값은 {kConfigRelative} 에만 쓴다. */
    enum class ProcessExitCode : int
    {{
{listEnumerator}
    }};

    /** @brief 종료 코드의 이름(요약 줄 · 보고)입니다. 표에 없는 코드면 nullptr 입니다. */
    constexpr const char* findProcessExitCodeLabel( int exitCode )
    {{
        switch ( exitCode )
        {{
{listCase}
            default:
                return nullptr;
        }}
    }}
}} // namespace sw
"""


def makeCMakeText(listRow: list[tuple[str, int, str]]) -> str:
    listLine = [f"# AUTO-GENERATED by Scripts/generate/ProcessExitCodes.py — do not edit. SSOT: {kConfigRelative}"]
    listLine += [f"set(SW_EXIT_CODE_{name} {code})" for name, code, _ in listRow]
    return "\n".join(listLine) + "\n"


def generateProcessExitCodes(headerPath: Path, cmakePath: Path) -> None:
    listRow = loadRows()
    writeGeneratedFile(headerPath, makeHeaderText(listRow), tag=kTag)
    writeGeneratedFile(cmakePath, makeCMakeText(listRow), tag=kTag)


def main(argv: list[str] | None = None) -> int:
    def addArgumentsInternal(parser: argparse.ArgumentParser) -> None:
        parser.add_argument("header", type=Path, help="쓸 C++ 헤더")
        parser.add_argument("cmake", type=Path, help="쓸 CMake 표")

    return runGenerator(argv, tag=kTag, description="ProcessExitCodes.json → C++ 열거형 · CMake 변수",
                        addArguments=addArgumentsInternal,
                        generate=lambda args: generateProcessExitCodes(args.header, args.cmake))


if __name__ == "__main__":
    sys.exit(main())
