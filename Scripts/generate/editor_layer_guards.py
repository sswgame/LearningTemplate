#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Scripts/generate/editor_layer_guards.py

에디터 층 표(`Config/Rules/Layers/EditorLayers.toml`)를 CMake 가 읽는 `EditorLayers.cmake` 로 옮긴다.

왜 린트가 아니라 빌드인가. `Source/Editor` 의 폴더는 층이고 아래 층은 위 층의 헤더를 include 하지 못한다. `#include` 글자를 읽는
린트는 직접 include 만 본다. 그래서 `Source/Editor/CMakeLists.txt` 가 층마다 OBJECT 라이브러리(부분)로 짓고, 부분마다 자기 층보다 위 층의
모든 헤더 자리에 `#error` 가드를 먼저 놓는다 — 위 층 헤더를 include 하면 컴파일이 멈춘다(전이 include 도 같다). 표는 여기서 한 번만 읽고
CMake 는 결과를 읽는다(`project_constants.py` → `ConfigVars.cmake` 와 같은 방식).

표가 폴더와 어긋나도 멈춘다(configure 가 서지 않는다) — 표에 없는 폴더는 층을 정하고 넣고, 폴더가 사라진 줄은 지운다.

층 이름: `Common/<하위 폴더>`(Common 바로 아래 파일은 `Common`), 그 밖의 최상위 폴더, `Source/Editor` 바로 아래 파일은 `<root>`.

"""

from __future__ import annotations

import re
from pathlib import Path

from common.layer_table import EDITOR_COMMON_FOLDER, EDITOR_ROOT_LAYER, get_layer_table_path, read_layer_table
from common.project_constants import DIR_SOURCE_EDITOR
from generate.generator_output import CodeGenerator, GeneratorError, write_generated_file
from common.paths import get_project_root

TAG = "EditorLayers"
RULE_FILE = get_layer_table_path("Editor")

HEADER = """# ==============================================================================
# AUTO-GENERATED by Scripts/generate/editor_layer_guards.py — do not edit.
#
# 출처: Config/Rules/Layers/EditorLayers.toml 의 [layer] · [prelude] · [panelViewGuard] · [panelViewAllowed] 와 Source/Editor 의 폴더.
# 쓰는 곳: Source/Editor/CMakeLists.txt — 층마다 부분을 짓고 위 층 헤더 자리에 #error 가드를 놓는다.
# ==============================================================================
"""


def _list_actual_layers(editor_dir: Path) -> list[str]:
    """`Source/Editor` 의 폴더에서 층 이름을 뽑는다."""
    list_layer: list[str] = []
    if any(child.is_file() for child in editor_dir.iterdir()):
        list_layer.append(EDITOR_ROOT_LAYER)
    for child in sorted(editor_dir.iterdir()):
        if not child.is_dir():
            continue
        if child.name != EDITOR_COMMON_FOLDER:
            list_layer.append(child.name)
            continue
        if any(entry.is_file() for entry in child.iterdir()):
            list_layer.append(EDITOR_COMMON_FOLDER)
        list_layer.extend(f"{EDITOR_COMMON_FOLDER}/{entry.name}" for entry in sorted(child.iterdir()) if entry.is_dir())
    return list_layer


def read_panel_view_default_guard(data: dict, root: Path) -> tuple[list[str], list[str]]:
    """`[panelViewGuard] defaultGuard`(기본 금지 폴더 정규식)과 `[panelViewAllowedFolders]`(폴더 접두) — 허용 목록 방식. 표가 낡으면 멈춘다."""
    list_default: list[str] = data["panelViewGuard"].get("defaultGuard", [])
    map_folder: dict[str, str] = data.get("panelViewAllowedFolders", {})
    for pattern in list_default:
        if not re.match(r"^\^[A-Za-z0-9_]+/$", pattern):
            raise GeneratorError(f"[panelViewGuard] defaultGuard 의 '{pattern}' 은 `^<Source 아래 최상위 폴더>/` 꼴이어야 한다")
    for folder, reason in map_folder.items():
        if not folder.endswith("/") or not (root / "Source" / folder).is_dir():
            raise GeneratorError(f"[panelViewAllowedFolders] 의 '{folder}' 가 Source 아래 폴더가 아니거나 '/' 로 끝나지 않는다 — 표를 고치세요")
        if not reason or not any(re.search(pattern, folder) for pattern in list_default):
            raise GeneratorError(f"[panelViewAllowedFolders] 의 {folder}: 까닭이 비었거나 기본 금지 폴더 밖이다(낡은 줄) — 표에서 지우세요")
    return list_default, list(map_folder)


def read_panel_view_guard(data: dict, root: Path, list_actual: list[str]) -> tuple[list[str], list[str], list[str]]:
    """`[panelViewGuard]` 의 View 경로 · 정규식과 `[panelViewAllowed]` 의 헤더 — CMake 가 층마다 MVVM View 부분에 가드를 놓는다. 표가 낡으면 멈춘다."""
    try:
        list_view: list[str] = data["panelViewGuard"]["views"]
        list_pattern: list[str] = data["panelViewGuard"]["patterns"]
        map_allowed: dict[str, str] = data["panelViewAllowed"]
    except KeyError as exception:
        raise GeneratorError(f"{RULE_FILE.name}: [panelViewGuard] views · patterns 와 [panelViewAllowed] 가 있어야 한다 ({exception!r})") from exception
    editor_dir = root / DIR_SOURCE_EDITOR
    for view in list_view:
        path = editor_dir / view
        if not path.exists() or any(character in view for character in '\\";$'):
            raise GeneratorError(f"[panelViewGuard] views 의 '{view}' 가 Source/Editor 아래에 없다(층 · 폴더 · 파일 경로) — 표를 고치세요")
        if not any(view == layer or view.startswith(layer + "/") for layer in list_actual if layer != EDITOR_ROOT_LAYER):
            raise GeneratorError(f"[panelViewGuard] views 의 '{view}' 가 어느 에디터 층에도 들지 않는다")
    for pattern in list_pattern:
        if any(character in pattern for character in '\\";$'):
            raise GeneratorError(f"[panelViewGuard] 의 정규식에 CMake 글자로 옮기지 못하는 문자가 있다: {pattern}")
        re.compile(pattern)
    for header, reason in map_allowed.items():
        if not (root / "Source" / header).is_file():
            raise GeneratorError(f"[panelViewAllowed] 의 파일이 없습니다: {header} — 표에서 지우거나 경로를 고치세요")
        list_any_guard = list_pattern + data["panelViewGuard"].get("defaultGuard", [])
        if not reason or not any(re.search(pattern, header) for pattern in list_any_guard):
            raise GeneratorError(f"[panelViewAllowed] 의 {header}: 까닭이 비었거나 금지 폴더 밖이다(낡은 줄) — 표에서 지우세요")
    return list_view, list_pattern, list(map_allowed)


def generate_editor_layer_guards(output_path: Path) -> None:
    data = read_layer_table("Editor")
    map_layer: dict[str, int] = data["layer"]
    root = get_project_root()
    editor_dir = root / DIR_SOURCE_EDITOR
    list_actual = _list_actual_layers(editor_dir)
    list_missing = [layer for layer in list_actual if layer not in map_layer]
    list_stale = [layer for layer in map_layer if layer not in list_actual]
    if list_missing:
        raise GeneratorError(f"층 표에 없는 에디터 층: {', '.join(list_missing)} — {RULE_FILE.name} 의 [layer] 에 층을 정해 넣으세요")
    if list_stale:
        raise GeneratorError(f"폴더가 없는 층 표 줄: {', '.join(list_stale)} — {RULE_FILE.name} 의 [layer] 에서 지우세요")
    for include in data.get("prelude", {}):
        if not include.startswith("Editor/") or not (root / "Source" / include).is_file():
            raise GeneratorError(f"[prelude] 의 파일이 없습니다: {include}")
    list_view, list_guard_pattern, list_allowed = read_panel_view_guard(data, root, list_actual)
    list_default_guard, list_allowed_folder = read_panel_view_default_guard(data, root)

    list_layer_number = sorted(set(map_layer.values()))
    list_line = [HEADER.rstrip("\n"), "", f'set(SW_EDITOR_LAYER_LIST "{";".join(str(number) for number in list_layer_number)}")']
    for number in list_layer_number:
        list_folder = [layer for layer in list_actual if map_layer[layer] == number]
        list_line.append(f'set(SW_EDITOR_LAYER_{number}_FOLDERS "{";".join(list_folder)}")')
    list_line.append(f'set(SW_EDITOR_PRELUDE_HEADERS "{";".join(data.get("prelude", {}))}")')
    list_line.append(f'set(SW_EDITOR_MVVM_VIEW_PATHS "{";".join(list_view)}")')
    list_line.append(f'set(SW_EDITOR_PANEL_VIEW_GUARD_REGEX "{";".join(list_guard_pattern)}")')
    list_line.append(f'set(SW_EDITOR_PANEL_VIEW_ALLOWED_HEADERS "{";".join(list_allowed)}")')
    list_line.append(f'set(SW_EDITOR_PANEL_VIEW_DEFAULT_GUARD_REGEX "{";".join(list_default_guard)}")')
    list_line.append(f'set(SW_EDITOR_PANEL_VIEW_ALLOWED_FOLDERS "{";".join(list_allowed_folder)}")')
    list_line.append("")
    write_generated_file(output_path, "\n".join(list_line), tag=TAG, summary=f"{len(list_actual)} folders · {len(list_layer_number)} layers")


class EditorLayerGuardsGenerator(CodeGenerator):
    def generate(self, output_dir: Path, game_name: str) -> None:
        generate_editor_layer_guards(output_dir / "EditorLayers.cmake")
