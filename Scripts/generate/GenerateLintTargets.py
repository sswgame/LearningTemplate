#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Scripts/generate/GenerateLintTargets.py

CMake 가 그대로 `include()` 할 린트 타깃·CTest 등록 파일(LintTargets.cmake)을 만듭니다. 린트는 `Scripts/lint/gate/CheckIncludeOrder.py` 하나다.

이 저장소가 `Constants.py` → `ConfigVars.cmake` 로 하고 있는 방식과 같다: **파이썬이 알고, CMake 는 결과를 읽는다.**

Usage:
  python Scripts/generate/GenerateLintTargets.py <output_cmake_file>
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Sequence

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # Scripts

from common.GeneratedFile import runGenerator, writeGeneratedFile  # noqa: E402

kTag = "GenerateLintTargets"

kHeader = """# ==============================================================================
# AUTO-GENERATED by Scripts/generate/GenerateLintTargets.py — do not edit.
# ==============================================================================
"""

#: 린트 하나 — CTest 이름이자 커스텀 타깃 이름, 스크립트(저장소 루트 기준), 빌드 출력 줄(영어 — 콘솔 코드페이지에서 한글이 깨진 전례), CTest 타임아웃(초).
kLintName = "CheckIncludeOrder"
kLintScriptRelPath = "Scripts/lint/gate/CheckIncludeOrder.py"
kLintBuildComment = "Checking Include Order rules..."
kLintTimeoutSeconds = 120


def emitTargetsInternal() -> str:
    """`sw_addRepoPythonTarget` 호출 — `cmake --build --target CheckIncludeOrder` 로 쓰는 그것."""
    return "\n".join([
        "# 린트를 따로 돌릴 수 있는 커스텀 타깃",
        "function(sw_addGeneratedLintTargets)",
        f'\tsw_addRepoPythonTarget({kLintName} "{kLintScriptRelPath}"',
        f'\t\tCOMMENT "{kLintBuildComment}"',
        '\t\tARGS --root "${CMAKE_SOURCE_DIR}"',
        "\t)",
        "endfunction()",
    ])


def emitTestsInternal() -> str:
    """CTest 등록 — 라벨은 `lint`. `SKIP_RETURN_CODE 77` 은 일부러 달지 않는다: 전체 훑기에서 새는 77 이 "건너뜀" 으로 읽혀 실패가 아닌 채로 지나가면 안 된다."""
    return "\n".join([
        "# CTest 등록. 게이트는 보고만 한다 — 고치는 것은 lint/fixer/ 의 픽서다.",
        "function(sw_registerGeneratedLintTests)",
        f"\tif(TARGET {kLintName})",
        f"\t\tsw_registerScriptTest({kLintName}",
        f'\t\t\tSCRIPT "{kLintScriptRelPath}"',
        '\t\t\tARGS --root "${CMAKE_SOURCE_DIR}"',
        f'\t\t\tLABELS "lint" TIMEOUT {kLintTimeoutSeconds})',
        "\tendif()",
        "endfunction()",
    ])


def generateLintTargets(outputPath: Path) -> None:
    content = "\n".join((kHeader, emitTargetsInternal(), "", emitTestsInternal(), ""))
    writeGeneratedFile(outputPath, content, tag=kTag, summary="1 lint")


def main(argv: Sequence[str] | None = None) -> int:
    return runGenerator(argv, tag=kTag, description="CMake 린트 타깃 · 테스트",
                        addArguments=lambda parser: parser.add_argument("output", type=Path, help="쓸 .cmake 파일"),
                        generate=lambda args: generateLintTargets(args.output))


if __name__ == "__main__":
    sys.exit(main())
