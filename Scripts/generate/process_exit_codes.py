"""
Scripts/generate/process_exit_codes.py

Config/Engine/ProcessExitCodes.json(프로세스 종료 코드 표의 단일 출처)을 읽어 C++ 헤더(sw/config/ProcessExitCodes.gen.h)와
CMake 표(ProcessExitCodes.cmake — `SW_EXIT_CODE_<name>`)를 생성합니다. 숫자는 JSON 에만 있다.

Usage:
  python Scripts/generate/process_exit_codes.py <output_header_path> <output_cmake_path>
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from generate.generator_output import GeneratorError, run_generator, write_generated_file  # noqa: E402
from common.paths import get_project_root  # noqa: E402

TAG = "ProcessExitCodes"
CONFIG_RELATIVE = "Config/Engine/ProcessExitCodes.json"


def load_rows() -> list[tuple[str, int, str]]:
    """(name, code, label) 줄 목록입니다. 이름 · 코드 · 라벨이 겹치거나 칸이 틀리면 오류로 멈춘다."""
    path = get_project_root() / CONFIG_RELATIVE
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        list_row = [(str(row["name"]), int(row["code"]), str(row["label"])) for row in data["exit_codes"]]
    except (OSError, KeyError, TypeError, ValueError) as exception:
        raise GeneratorError(f"{CONFIG_RELATIVE}: {exception}") from exception
    for column, kind in ((0, "name"), (1, "code"), (2, "label")):
        list_value = [row[column] for row in list_row]
        if len(set(list_value)) != len(list_value):
            raise GeneratorError(f"{CONFIG_RELATIVE}: duplicate {kind} in exit_codes")
    if any(not name.isidentifier() for name, _, _ in list_row):
        raise GeneratorError(f"{CONFIG_RELATIVE}: every name must be a C++ identifier")
    return list_row


def make_header_text(list_row: list[tuple[str, int, str]]) -> str:
    list_enumerator = "\n".join(f"        {name} = {code}," for name, code, _ in list_row)
    list_case = "\n".join(f'            case {code}:\n                return "{label}";' for _, code, label in list_row)
    return f"""#pragma once
// AUTO-GENERATED by Scripts/generate/process_exit_codes.py — do not edit.
// SSOT: {CONFIG_RELATIVE}

namespace sw
{{
    /** @brief App 이 밖으로 내는 프로세스 종료 코드입니다. 값은 {CONFIG_RELATIVE} 에만 쓴다. */
    enum class ProcessExitCode : int
    {{
{list_enumerator}
    }};

    /** @brief 종료 코드의 이름(요약 줄 · 보고)입니다. 표에 없는 코드면 nullptr 입니다. */
    constexpr const char* findProcessExitCodeLabel( int exitCode )
    {{
        switch ( exitCode )
        {{
{list_case}
            default:
                return nullptr;
        }}
    }}
}} // namespace sw
"""


def make_cmake_text(list_row: list[tuple[str, int, str]]) -> str:
    list_line = [f"# AUTO-GENERATED by Scripts/generate/process_exit_codes.py — do not edit. SSOT: {CONFIG_RELATIVE}"]
    list_line += [f"set(SW_EXIT_CODE_{name} {code})" for name, code, _ in list_row]
    return "\n".join(list_line) + "\n"


def generate_process_exit_codes(header_path: Path, cmake_path: Path) -> None:
    list_row = load_rows()
    write_generated_file(header_path, make_header_text(list_row), tag=TAG)
    write_generated_file(cmake_path, make_cmake_text(list_row), tag=TAG)


def main(argv: list[str] | None = None) -> int:
    def _add_arguments(parser: argparse.ArgumentParser) -> None:
        parser.add_argument("header", type=Path, help="쓸 C++ 헤더")
        parser.add_argument("cmake", type=Path, help="쓸 CMake 표")

    return run_generator(argv, tag=TAG, description="ProcessExitCodes.json → C++ 열거형 · CMake 변수",
                        add_arguments=_add_arguments,
                        generate=lambda args: generate_process_exit_codes(args.header, args.cmake))


if __name__ == "__main__":
    sys.exit(main())
