#!/usr/bin/env python3
"""
Scripts/setup/InstallGitHooks.py

Git 훅을 .git/hooks/ 디렉터리에 설치합니다 — pre-commit(커밋 시 린트 · 포맷 검사), pre-push(main 으로 가는 트리에 전체 빌드 증거).
"""

from __future__ import annotations

import argparse
import os
import platform
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.Paths import getProjectRoot
from common.ExitCode import ExitCode  # noqa: E402


def installPreCommitHook(projectRoot: Path | None = None) -> bool:
    """
    .git/hooks/pre-commit 훅을 설치하여 커밋 시 PreCommitLint.py가 자동 실행되도록 합니다.
    """
    root = projectRoot or getProjectRoot()
    gitDir = root / ".git"

    if not gitDir.is_dir():
        return False

    hooksDir = gitDir / "hooks"
    hooksDir.mkdir(parents=True, exist_ok=True)

    preCommitPath = hooksDir / "pre-commit"
    hookScript = (
        "#!/bin/sh\n"
        "# Auto-generated by SW Engine setup\n\n"
        "if command -v py >/dev/null 2>&1; then\n"
        "  py -3 -m Scripts lint\n"
        "elif command -v python3 >/dev/null 2>&1; then\n"
        "  python3 -m Scripts lint\n"
        "elif command -v python >/dev/null 2>&1; then\n"
        "  python -m Scripts lint\n"
        "else\n"
        '  echo "[pre-commit] Error: Python was not found in PATH." >&2\n'
        "  exit 1\n"
        "fi\n\n"
        "if [ $? -ne 0 ]; then\n"
        "  exit 1\n"
        "fi\n"
    )

    preCommitPath.write_text(hookScript, encoding="utf-8")
    if platform.system() != "Windows":
        os.chmod(preCommitPath, 0o755)

    print(f"[InstallGitHooks] Git pre-commit 훅이 설치되었습니다: {preCommitPath}")
    return True


def installPrePushHook(projectRoot: Path | None = None) -> bool:
    """
    .git/hooks/pre-push 훅을 설치합니다. main 으로 가는 커밋의 트리에 전체 빌드(all AllTests) 증거가 없으면 push 를 막는다
    (`Scripts/dev/RunFullBuild.py` — 브랜치 검증이 바꾼 영역만 지으면 병합 뒤에야 깨진다).
    """
    root = projectRoot or getProjectRoot()
    gitDir = root / ".git"
    if not gitDir.is_dir():
        return False
    hooksDir = gitDir / "hooks"
    hooksDir.mkdir(parents=True, exist_ok=True)
    prePushPath = hooksDir / "pre-push"
    hookScript = (
        "#!/bin/sh\n"
        "# Auto-generated by SW Engine setup\n\n"
        "if command -v py >/dev/null 2>&1; then\n"
        "  py -3 -m Scripts full-build check-push\n"
        "elif command -v python3 >/dev/null 2>&1; then\n"
        "  python3 -m Scripts full-build check-push\n"
        "elif command -v python >/dev/null 2>&1; then\n"
        "  python -m Scripts full-build check-push\n"
        "else\n"
        '  echo "[pre-push] Error: Python was not found in PATH." >&2\n'
        "  exit 1\n"
        "fi\n"
    )
    prePushPath.write_text(hookScript, encoding="utf-8")
    if platform.system() != "Windows":
        os.chmod(prePushPath, 0o755)
    print(f"[InstallGitHooks] Git pre-push 훅이 설치되었습니다: {prePushPath}")
    return True


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(description="Git pre-commit 훅(PreCommitLint) · pre-push 훅(전체 빌드 증거)을 설치한다 — 인자 없음").parse_args(argv)
    if not installPreCommitHook() or not installPrePushHook():
        print("[InstallGitHooks] .git 디렉터리를 찾을 수 없습니다.", file=sys.stderr)
        return ExitCode.Violation
    return ExitCode.Passed


if __name__ == "__main__":
    sys.exit(main())
