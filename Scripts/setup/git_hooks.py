#!/usr/bin/env python3
"""
Scripts/setup/git_hooks.py

Git 훅을 .git/hooks/ 디렉터리에 설치합니다 — pre-commit(커밋 시 린트 · 포맷 검사).
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.paths import get_project_root
from common.host_platform import is_windows_host
from common.exit_code import ExitCode  # noqa: E402


def install_pre_commit_hook(project_root: Path | None = None) -> bool:
    """
    .git/hooks/pre-commit 훅을 설치하여 커밋 시 pre_commit.py 가 자동 실행되도록 합니다.
    """
    root = project_root or get_project_root()
    git_dir = root / ".git"

    if not git_dir.is_dir():
        return False

    hooks_dir = git_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)

    pre_commit_path = hooks_dir / "pre-commit"
    hook_script = (
        "#!/bin/sh\n"
        "# Auto-generated by SW Engine setup\n\n"
        "if command -v py >/dev/null 2>&1; then\n"
        "  py -3 -m Scripts lint\n"
        "elif command -v python3 >/dev/null 2>&1; then\n"
        "  python3 -m Scripts lint\n"
        "elif command -v python >/dev/null 2>&1; then\n"
        "  python -m Scripts lint\n"
        "else\n"
        '  echo "[pre-commit] Error: Python was not found in PATH." >&2\n'
        "  exit 1\n"
        "fi\n\n"
        "if [ $? -ne 0 ]; then\n"
        "  exit 1\n"
        "fi\n"
    )

    pre_commit_path.write_text(hook_script, encoding="utf-8")
    if not is_windows_host():
        os.chmod(pre_commit_path, 0o755)

    print(f"[GitHooks] Git pre-commit 훅이 설치되었습니다: {pre_commit_path}")
    return True


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(description="Git pre-commit 훅(PreCommit)을 설치한다 — 인자 없음").parse_args(argv)
    if not install_pre_commit_hook():
        print("[GitHooks] .git 디렉터리를 찾을 수 없습니다.", file=sys.stderr)
        return ExitCode.VIOLATION
    return ExitCode.PASSED


if __name__ == "__main__":
    sys.exit(main())
